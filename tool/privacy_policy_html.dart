// Renders the privacy policy to the static page Firebase Hosting serves.
//
//   dart run tool/privacy_policy_html.dart
//
// Google Play needs the policy at a public URL, and the app needs it readable
// without a browser. Rather than keep two documents honest by hand, the page is
// generated from `PrivacyPolicy` — the same constant the in-app screen reads —
// and `test/privacy_policy_test.dart` fails if the checked-in file is not what
// this produces today. Edit the policy, run this, commit both.
//
// Lives in tool/ rather than lib/ so no HTML rendering is compiled into the
// shipped app.

import 'dart:io';

import 'package:void_factor/features/legal/privacy_policy.dart';

/// Where the generated page is written, relative to the package root.
const String outputPath = 'firebase_hosting/public/privacy.html';

void main() {
  File(outputPath).writeAsStringSync(renderPrivacyPolicyHtml());
  stdout.writeln('wrote $outputPath');
}

