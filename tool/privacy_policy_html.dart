String _section(PolicySection section) {
  final paragraphs = section.paragraphs
      .map((p) => '            <p>${_escape(p)}</p>')
      .join('\n');
  return '        <section>\n'
      '            <h2>${_escape(section.title)}</h2>\n'
      '$paragraphs\n'
      '        </section>';
}

/// Policy text is prose, not markup. Anything that could be read as a tag or an
/// entity is escaped, so a stray `&` in a future edit cannot break the page.
String _escape(String text) => text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
